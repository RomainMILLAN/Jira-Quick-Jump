/**
 * Vendors the author signature stylesheet from the pinned submodule.
 *
 * The submodule is a LOCAL DEVELOPMENT TOOL: it gives a traceable, commit-pinned
 * update path. It is deliberately NOT used by CI, which stays hermetic and clones
 * no external repository. The committed copy is what ships, and it is the only
 * thing a clone without --recurse-submodules needs.
 *
 * The provenance header is not decoration: `test/structure.test.js` asserts it,
 * which is what puts the project in line with the SPIRIT of its own
 * "no third-party code ever ships inside the extension" test -- that one only
 * looks at package.json.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "vendor", "rm-tag", "tag.css");
const TARGET = join(ROOT, "src", "ui", "author-signature.css");

if (!existsSync(SOURCE)) {
  console.error("vendor/rm-tag is missing. Run: git submodule update --init");
  process.exit(1);
}

const sha = execFileSync("git", ["-C", join(ROOT, "vendor", "rm-tag"), "rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();

const header = `/*!
 * Vendored from github.com/RomainMILLAN/Romain-MILLAN-Tag@${sha}
 * Copyright (c) 2024-2025 Romain MILLAN -- MIT License
 *
 * DO NOT EDIT THIS FILE. It must stay a byte-for-byte mirror of upstream, or
 * \`make sync-signature\` reports a drift on every run. Theme it from
 * src/ui/sections.css through the published --rm-tag-* variables instead.
 *
 * To update: git submodule update --remote vendor/rm-tag && make sync-signature
 */
`;

writeFileSync(TARGET, header + readFileSync(SOURCE, "utf8"));
console.log(`src/ui/author-signature.css synced from Romain-MILLAN-Tag@${sha.slice(0, 12)}`);
